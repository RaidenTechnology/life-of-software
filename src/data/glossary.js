const Glossary = {
  // language layer wins, then the shared one, then nothing. Returns
  // { word, what, ex } or null — callers skip nulls rather than pad.
  lookup(langName, word) {
    // hasOwnProperty, not plain indexing. These are plain objects, so a pattern
    // that happens to name an Object.prototype member -- and `constructor` is a
    // real word in a real list -- resolved to the INHERITED function: truthy, so
    // it counted as covered, then rendered `what`/`ex` as undefined. A blank row
    // on the review card, from a lookup that reported success. (`toString`,
    // `valueOf` and `__proto__` are the same hazard waiting for a future word
    // list.) Own keys only, so a miss is a miss.
    const own = (o, k) => o && Object.prototype.hasOwnProperty.call(o, k) ? o[k] : null;
    const e = own(G_LANG[langName], word) || own(G_SHARED, word);
    return e ? { word: word, what: e[0], ex: e[1] } : null;
  },

  // every explained pattern from `words`, in the order given, capped.
  review(langName, words, cap) {
    const out = [];
    for (const w of words) {
      const e = this.lookup(langName, w);
      if (e) out.push(e);
      if (cap && out.length >= cap) break;
    }
    return out;
  },

  // how much of a language's list the glossary can actually teach — used to
  // decide whether the review card is worth showing at all.
  coverage(lang) {
    let n = 0;
    for (const w of lang.words) if (this.lookup(lang.name, w)) n++;
    return n / lang.words.length;
  }
};
